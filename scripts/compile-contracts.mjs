// Compiles contracts/*.sol with solc-js and writes ABI + bytecode to src/lib/contract-artifacts.ts
// Usage: npm run compile:contracts
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import solc from "solc";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const files = ["MockUSDC.sol", "UpHealthSLA.sol"];
const sources = Object.fromEntries(
  files.map((f) => [f, { content: fs.readFileSync(path.join(root, "contracts", f), "utf8") }]),
);
const input = {
  language: "Solidity",
  sources,
  settings: {
    optimizer: { enabled: true, runs: 200 },
    evmVersion: "paris",
    outputSelection: { "*": { "*": ["abi", "evm.bytecode.object"] } },
  },
};
const output = JSON.parse(solc.compile(JSON.stringify(input)));
const errors = (output.errors ?? []).filter((e) => e.severity === "error");
for (const e of output.errors ?? []) console.log(`[solc ${e.severity}] ${e.formattedMessage}`);
if (errors.length) process.exit(1);

const pick = (file, name) => output.contracts[file][name];
const usdc = pick("MockUSDC.sol", "MockUSDC");
const sla = pick("UpHealthSLA.sol", "UpHealthSLA");
const banner = `// AUTO-GENERATED by scripts/compile-contracts.mjs (solc ${solc.version()}). Do not edit.\n`;
const body =
  banner +
  `export const mockUsdcAbi = ${JSON.stringify(usdc.abi, null, 2)} as const;\n\n` +
  `export const mockUsdcBytecode = "0x${usdc.evm.bytecode.object}" as const;\n\n` +
  `export const upHealthSlaAbi = ${JSON.stringify(sla.abi, null, 2)} as const;\n\n` +
  `export const upHealthSlaBytecode = "0x${sla.evm.bytecode.object}" as const;\n\n` +
  `export const SOLC_VERSION = ${JSON.stringify(solc.version())};\n\n` +
  `export const contractSources = ${JSON.stringify(Object.fromEntries(files.map((f) => [f, sources[f].content])), null, 2)} as const;\n`;
fs.writeFileSync(path.join(root, "src/lib/contract-artifacts.ts"), body);
console.log("Wrote src/lib/contract-artifacts.ts", { usdcBytes: usdc.evm.bytecode.object.length / 2, slaBytes: sla.evm.bytecode.object.length / 2 });
